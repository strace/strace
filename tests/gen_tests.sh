usage()
{
	cat >&2 <<EOF
Usage: $0 [<input> [<output>]]

Generate test script(s) from <input> table.
If a <output> is specified, generate the script for this test only,
otherwise generate scripts for all tests specified in <input> table.
EOF
	exit 1
}

input="${0%/*}/gen_tests.in"
[ $# -eq 0 ] || { input="$1"; shift; }
output=
[ $# -eq 0 ] || { output="$1"; shift; }
[ $# -eq 0 ] || usage

if [ -n "$output" ]; then
	match="${output##*/}"
	match="${match%.gen.test}"
	[ -n "$match" ] || usage
else
	match=
	dir="$(dirname "$input")"
fi

names=
pidns_names=
tmp_output=
trap '[ -z "$tmp_output" ] || rm -f -- "$tmp_output"' 0

while read -r name arg0 args; do {
	[ -n "${name###*}" ] || continue
	if [ -z "$match" ]; then
		names="$names $name"
		if [ "$arg0" = '+procfs-pidns.sh' ]; then
			pidns_names="$pidns_names $name"
		fi
		output="$dir/$name.gen.test"
	else
		[ "$match" = "$name" ] || continue
	fi

	hdr="\
#!/bin/sh -efu
# Generated by $0 from $input ($name $arg0 $args); do not edit."

	# A generated test may be sourced while another build regenerates it.
	# Replace the file atomically so the reader keeps its original contents.
	tmp_output="$output.$$"
	case "$arg0" in
		+*)
		cat <<-EOF
		$hdr
		set -- $args
		. "\${srcdir=.}/${arg0#+}"
		EOF
		;;

		# Tests that rely on syscall tampering require additional checks
		# implemented in the scno_tamperng.sh.
		-einject=*|--inject=*)
		case " $args " in
			*\ -y\ *)
			cat <<-EOF
			$hdr
			. "\${srcdir=.}/scno_tampering.sh"
			run_strace_match_diff $arg0 $args
			EOF
			;;
			*)
			cat <<-EOF
			$hdr
			. "\${srcdir=.}/scno_tampering.sh"
			ret=0
			../$name || ret=\$?
			if [ "\$ret" -eq 77 ]; then
				exit 77
			fi
			run_strace $arg0 $args "../$name" > "\$EXP"
			match_diff "\$LOG" "\$EXP"
			EOF
			;;
		esac
		;;

		''|-*)
		cat <<-EOF
		$hdr
		. "\${srcdir=.}/init.sh"
		run_strace_match_diff $arg0 $args
		EOF
		;;

		*)
		cat <<-EOF
		$hdr
		. "\${srcdir=.}/init.sh"
		$arg0 $args
		EOF
		;;
	esac > "$tmp_output"

	chmod a+x "$tmp_output"
	mv -f -- "$tmp_output" "$output"
} < /dev/null; done < "$input"

if [ -n "$names" ]; then
	{
		printf '# Generated by %s from %s; do not edit.\n' "$0" "$input"
		printf 'GEN_TESTS ='
		printf ' %s.gen.test' $names
		echo
		target='$(srcdir)/%s.gen.test'
		dep1='$(abs_srcdir)/gen_tests.sh'
		dep2='$(srcdir)/gen_tests.in'
		recipe='$(AM_V_GEN) '"$dep1 $dep2"' $@'
		printf "\\n$target: $dep1 $dep2\\n\\t$recipe\\n" $names
		for pidns_name in $pidns_names; do
			name="${pidns_name%--pidns}"
			[ "$pidns_name" != "$name" ] ||
				continue
			printf '\n$(srcdir)/%s.gen.test: $(srcdir)/%s.gen.test\n' \
				"$pidns_name" "$name"
		done
	} > "$dir/gen_tests.am"
fi
